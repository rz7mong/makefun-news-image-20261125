"""Entry point for the make.fun news-image-20261125 bounty.

Copies the pre-built entry.png (generated by gen_image.py at build
time) into the harness output directory. It does NOT run the
generator and does NOT use the network: the image is a fixed,
deterministic artifact.
"""

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")


def main():
    src = os.path.join(HERE, "entry.png")
    os.makedirs(OUT_DIR, exist_ok=True)
    shutil.copyfile(src, os.path.join(OUT_DIR, "entry.png"))


if __name__ == "__main__":
    main()
